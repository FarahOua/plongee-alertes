"""Accès à la base Postgres (Supabase). Une connexion par opération, suffisant pour ce volume.

Le code applicatif écrit ses requêtes avec des « ? » ; ce module les traduit en « %s » pour psycopg.
"""
from contextlib import contextmanager

from . import config

TABLES = ("users", "login_codes", "sessions", "subscriptions", "forecast_cache", "daily_reports", "email_log")

_NOW_TEXT = "(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))"

SCHEMA = f"""
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    created_at TEXT NOT NULL DEFAULT {_NOW_TEXT}
);

CREATE TABLE IF NOT EXISTS login_codes (
    email TEXT PRIMARY KEY,
    code_hash TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS subscriptions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lon DOUBLE PRECISION NOT NULL,
    start_date TEXT NOT NULL,          -- AAAA-MM-JJ, heure locale du spot
    end_date TEXT NOT NULL,
    send_time TEXT NOT NULL,           -- HH:MM, heure locale du spot
    timezone TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','paused','ended')),
    public_token TEXT NOT NULL UNIQUE, -- désabonnement et rapport web sans connexion
    last_sent_on TEXT,
    created_at TEXT NOT NULL DEFAULT {_NOW_TEXT}
);

CREATE TABLE IF NOT EXISTS forecast_cache (
    cache_key TEXT PRIMARY KEY,
    fetched_at TEXT NOT NULL,
    payload TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS daily_reports (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id INTEGER NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
    report_date TEXT NOT NULL,
    report_json TEXT NOT NULL,
    text_json TEXT NOT NULL,
    html TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT {_NOW_TEXT},
    UNIQUE (subscription_id, report_date)
);

CREATE TABLE IF NOT EXISTS email_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id INTEGER NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
    report_date TEXT NOT NULL,
    status TEXT NOT NULL,
    detail TEXT,
    sent_at TEXT NOT NULL DEFAULT {_NOW_TEXT},
    UNIQUE (subscription_id, report_date)  -- jamais deux envois le même jour
);
"""


def _statements() -> list[str]:
    statements = [part.strip() for part in SCHEMA.split(";") if part.strip()]
    # Supabase expose les tables du schéma public par son API REST : RLS sans aucune règle = accès
    # refusé à la clé « anon ». Notre serveur se connecte avec le rôle postgres, non concerné.
    statements += [f"ALTER TABLE {name} ENABLE ROW LEVEL SECURITY" for name in TABLES]
    return statements


class _Row(dict):
    """Ligne lisible par nom (row["id"]) et par position (row[0])."""

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    names = [column.name for column in cursor.description] if cursor.description else []
    return lambda values: _Row(zip(names, values))


class _Connection:
    """Enveloppe fine autour de psycopg : traduit les « ? » en « %s »."""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql: str, params=()):
        return self._conn.execute(sql.replace("?", "%s"), params)

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        self._conn.close()


def _connect() -> _Connection:
    if not config.DATABASE_URL:
        raise RuntimeError("DATABASE_URL manquant dans .env (chaîne de connexion Postgres de Supabase).")
    try:
        import psycopg
    except ImportError as exc:
        raise RuntimeError('Paquet manquant : pip install "psycopg[binary]"') from exc
    # prepare_threshold=None : compatible avec le pooler « transaction » de Supabase (port 6543)
    conn = psycopg.connect(config.DATABASE_URL, row_factory=_row_factory, prepare_threshold=None,
                           connect_timeout=15)
    return _Connection(conn)


@contextmanager
def get_db():
    conn = _connect()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db() -> None:
    with get_db() as conn:
        for statement in _statements():
            conn.execute(statement)


def describe() -> str:
    """Cible de la base, sans le mot de passe (pour les messages)."""
    return "Postgres " + config.DATABASE_URL.rsplit("@", 1)[-1]


def row_to_dict(row) -> dict:
    return dict(row) if row is not None else None
